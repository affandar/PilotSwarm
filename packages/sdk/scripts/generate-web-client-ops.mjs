#!/usr/bin/env node
/**
 * Generate the web management client's operation methods from the protocol
 * table.
 *
 * `packages/sdk/api/src/protocol.js` is already the single source of truth for
 * the portal's Express routes, `ApiClient`'s request building, and the API
 * reference docs. The web management client was the one consumer that did not
 * derive from it, and it drifted: 71 hand-written methods against 115
 * operations, with 30 methods reachable only through the direct (datastore)
 * client — including the session-sharing ops, which are the authorization
 * primitives themselves.
 *
 * This script closes that by emitting a method per operation. Hand-written
 * ergonomic methods still win: `installGeneratedOpMethods` never overwrites a
 * method the class already defines, so signatures like
 * `setSessionModel(sessionId, model, opts)` keep working for their existing
 * callers. Generated methods take a single flat params object matching the
 * table.
 *
 * Run: npm run generate:web-ops -w packages/sdk
 *
 * Pass an output path to write elsewhere — the coverage test uses this to
 * check freshness without mutating the checked-in file (a self-healing test
 * would fail once and then pass on retry, hiding the staleness in CI).
 */

import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, resolve } from "node:path";

const here = dirname(fileURLToPath(import.meta.url));
const OUT = process.argv[2] ? resolve(process.argv[2]) : resolve(here, "../src/web/generated-op-methods.ts");
const CLIENT = resolve(here, "../src/web/web-management-client.ts");

const { OPERATIONS } = await import(resolve(here, "../api/src/protocol.js"));

/**
 * Method names the class already declares. These keep their ergonomic
 * signatures — `setSessionModel(sessionId, model, opts)` rather than a flat
 * params object — so they are omitted from the generated interface (a
 * declaration merge cannot redeclare a member with a different signature) and
 * skipped by the runtime install.
 */
const handWritten = new Set();
for (const m of readFileSync(CLIENT, "utf8").matchAll(/^\s{4}(?:async\s+)?([a-zA-Z][a-zA-Z0-9_]*)\s*[(<]/gm)) {
    handWritten.add(m[1]);
}
for (const keyword of ["if", "for", "while", "switch", "catch", "return", "constructor"]) handWritten.delete(keyword);

/** Table param `type` → TypeScript type. Body params carry no type and are
 *  frequently structured (`options`, `input`, `patch`), so they stay `any`. */
function tsType(spec) {
    if (spec.in === "body") return "any";
    switch (spec.type) {
        case "number": return "number";
        case "boolean": return "boolean";
        case "json": return "any";
        default: return "string";
    }
}

function paramsType(op) {
    const entries = Object.entries(op.params || {});
    if (entries.length === 0) return "Record<string, never>";
    const fields = entries.map(([name, spec]) => {
        // Path params are structural — the route cannot be built without them.
        const optional = spec.in === "path" ? "" : "?";
        return `        ${name}${optional}: ${tsType(spec)};`;
    });
    return `{\n${fields.join("\n")}\n    }`;
}

function jsdoc(op) {
    const summary = String(op.summary || "").replace(/\*\//g, "*\\/");
    return [
        "    /**",
        `     * ${summary}`,
        `     * @remarks \`${op.method} ${op.path}\` — access: \`${op.access}\`${op.admin ? " (admin)" : ""}`,
        "     */",
    ].join("\n");
}

const sorted = [...OPERATIONS].sort((a, b) => a.name.localeCompare(b.name));
const generatedOps = sorted.filter((op) => !handWritten.has(op.name));

const methods = generatedOps
    .map((op) => {
        const params = paramsType(op);
        const arg = params === "Record<string, never>" ? "params?: Record<string, never>" : `params: ${params}`;
        return `${jsdoc(op)}\n    ${op.name}(${arg}): Promise<any>;`;
    })
    .join("\n\n");

const names = sorted.map((op) => `    ${JSON.stringify(op.name)},`).join("\n");
const handWrittenNames = sorted
    .filter((op) => handWritten.has(op.name))
    .map((op) => `    ${JSON.stringify(op.name)},`)
    .join("\n");

const out = `// @generated by packages/sdk/scripts/generate-web-client-ops.mjs — DO NOT EDIT.
// Regenerate: npm run generate:web-ops -w packages/sdk
//
// One method per entry in the protocol table (packages/sdk/api/src/protocol.js),
// so the web management client cannot drift from the operations the Web API
// actually exposes. See contract test: web-client-op-coverage.

/** Every operation name in the protocol table, sorted. */
export const GENERATED_OP_NAMES: readonly string[] = [
${names}
];

/**
 * Operations the client implements by hand, with ergonomic (non-flat)
 * signatures. These are omitted from \`GeneratedOpMethods\` and skipped by the
 * runtime install — they are covered, not missing.
 */
export const HAND_WRITTEN_OP_NAMES: readonly string[] = [
${handWrittenNames}
];

/**
 * Operation methods installed onto the web management client. Each takes the
 * operation's params as a single flat object and resolves the JSON result.
 *
 * Declaration-merged into \`WebPilotSwarmManagementClient\`. Only operations the
 * class does not already implement appear here.
 */
export interface GeneratedOpMethods {
${methods}
}

/**
 * Install a method per operation onto \`proto\`, skipping any name the class
 * already defines. Hand-written methods win — that is what keeps existing
 * ergonomic signatures (and their callers) working.
 *
 * @param proto prototype to install onto
 * @param callOp \`(self, name, params) => Promise<any>\` invoked by each method
 * @returns the operation names actually installed
 */
export function installGeneratedOpMethods(
    proto: object,
    callOp: (self: any, name: string, params: Record<string, unknown>) => Promise<any>,
): string[] {
    const installed: string[] = [];
    for (const name of GENERATED_OP_NAMES) {
        if (Object.prototype.hasOwnProperty.call(proto, name)) continue;
        Object.defineProperty(proto, name, {
            value: function (params: Record<string, unknown> = {}) {
                return callOp(this, name, params);
            },
            writable: true,
            configurable: true,
            enumerable: false,
        });
        installed.push(name);
    }
    return installed;
}
`;

writeFileSync(OUT, out, "utf8");
console.log(`generated ${sorted.length} operation methods → ${OUT}`);
