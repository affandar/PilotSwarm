#!/usr/bin/env node
/**
 * Generate the canonical Web API operation surface from the protocol table.
 *
 * `packages/sdk/api/src/protocol.js` is the single source of truth for the
 * portal's Express routes, `ApiClient`'s request building, and the API
 * reference docs. This script derives the client-side surface from it:
 *
 *   - `ManagementOps` — one method per operation, params shaped exactly like
 *     the wire (path/query/body fields flat, as the table declares them).
 *   - `createManagementOps(callOp)` — a factory producing that surface bound
 *     to a transport callback.
 *
 * The web management client exposes the result as `client.ops` — complete by
 * construction, so a new operation is callable (and type-visible) the moment
 * it lands in the table. The client's hand-written ergonomic methods are
 * sugar over this layer; they are allowed to be partial, `ops` is not.
 *
 * Run: npm run generate:web-ops -w packages/sdk
 *
 * Pass an output path to write elsewhere — the coverage test uses this to
 * check freshness without mutating the checked-in file (a self-healing test
 * would fail once and then pass on retry, hiding the staleness in CI).
 */

import { writeFileSync } from "node:fs";
import { fileURLToPath, pathToFileURL } from "node:url";
import { dirname, resolve } from "node:path";

const here = dirname(fileURLToPath(import.meta.url));
const OUT = process.argv[2] ? resolve(process.argv[2]) : resolve(here, "../src/web/generated-op-methods.ts");

const { OPERATIONS } = await import(pathToFileURL(resolve(here, "../api/src/protocol.js")).href);

/** Table param `type` → TypeScript type. Body params carry no type and are
 *  frequently structured (`options`, `input`, `patch`), so they stay `any`. */
function tsType(spec) {
    if (spec.in === "body") return "any";
    switch (spec.type) {
        case "number": return "number";
        case "boolean": return "boolean";
        case "json": return "any";
        default: return "string";
    }
}

function paramsType(op) {
    const entries = Object.entries(op.params || {});
    if (entries.length === 0) return "Record<string, never>";
    const fields = entries.map(([name, spec]) => {
        // Path params are structural — the route cannot be built without them.
        const optional = spec.in === "path" ? "" : "?";
        return `        ${name}${optional}: ${tsType(spec)};`;
    });
    return `{\n${fields.join("\n")}\n    }`;
}

function jsdoc(op) {
    const summary = String(op.summary || "").replace(/\*\//g, "*\\/");
    return [
        "    /**",
        `     * ${summary}`,
        `     * @remarks \`${op.method} ${op.path}\` — access: \`${op.access}\`${op.admin ? " (admin)" : ""}`,
        "     */",
    ].join("\n");
}

const sorted = [...OPERATIONS].sort((a, b) => a.name.localeCompare(b.name));

const methods = sorted
    .map((op) => {
        const params = paramsType(op);
        const arg = params === "Record<string, never>" ? "params?: Record<string, never>" : `params: ${params}`;
        return `${jsdoc(op)}\n    ${op.name}(${arg}): Promise<any>;`;
    })
    .join("\n\n");

const names = sorted.map((op) => `    ${JSON.stringify(op.name)},`).join("\n");

const factoryLines = sorted
    .map((op) => `        ${op.name}: (params: Record<string, unknown> = {}) => callOp(${JSON.stringify(op.name)}, params),`)
    .join("\n");

const out = `// @generated by packages/sdk/scripts/generate-web-client-ops.mjs — DO NOT EDIT.
// Regenerate: npm run generate:web-ops -w packages/sdk
//
// Derived from the protocol table (packages/sdk/api/src/protocol.js): the
// complete Web API operation surface, wire-shaped. Exposed by the web
// management client as \`client.ops\`. See contract test: web-client-op-coverage.

/** Every operation name in the protocol table, sorted. */
export const GENERATED_OP_NAMES: readonly string[] = [
${names}
];

/**
 * The canonical Web API surface: one method per protocol-table operation.
 * Params are wire-shaped — exactly the fields the table declares for the
 * operation, flat. Path params are required; query/body params are optional
 * at the type level (the server validates).
 *
 * This is the layer that cannot drift: it is generated from the same table
 * the server generates its routes from.
 */
export interface ManagementOps {
${methods}
}

/**
 * Build the operation surface bound to a transport callback.
 *
 * @param callOp invoked as \`(opName, params)\`; must resolve the JSON result
 */
export function createManagementOps(
    callOp: (name: string, params: Record<string, unknown>) => Promise<any>,
): ManagementOps {
    return {
${factoryLines}
    };
}
`;

writeFileSync(OUT, out, "utf8");
console.log(`generated ${sorted.length} operations → ${OUT}`);
